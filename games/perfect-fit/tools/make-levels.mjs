/* Perfect Fit — converts stazzi's shipped campaign (apps/casual/perfect-fit/src/levels/levels.ts, the 50 levels of LEVELS;
   extended.ts 51–56 and large.ts 57 are not connected in stazzi and are not ported) into games/perfect-fit/levels.js.
   Solutions are stazzi's own verified solutions (generator tools/make-campaign.ts, seed 6270). Difficulty = stazzi's label:
   easy -> 1, medium -> 2, hard/expert -> 3.
   Run from the repo root: node --experimental-strip-types games/perfect-fit/tools/make-levels.mjs > games/perfect-fit/levels.js */
const { LEVELS } = await import(process.env.STAZZI_LEVELS || '/home/user/stazzi/apps/casual/perfect-fit/src/levels/levels.ts');
const D = { easy: 1, medium: 2, hard: 3, expert: 3 };
const j = (x) => JSON.stringify(x);
const pc = (p) => '[' + p.map(([r, c]) => r + ',' + c).join(', ') + ']';
const rows = LEVELS.map((l) => {
  const parts = ['map: ' + j(l.map).replace(/","/g, '", "'), 'nums: ' + j(l.numbers)];
  if (l.builderMask) parts.push('mask: ' + j(l.builderMask).replace(/","/g, '", "'));
  if (l.clues) parts.push('clues: ' + j(l.clues.map((c) => [c.row, c.col, c.size])));
  if (l.pairs) parts.push('pairs: ' + j(l.pairs.map(([a, b]) => [...a, ...b])));
  if (l.seams) parts.push('seams: ' + j(l.seams.map(([a, b]) => [...a, ...b])));
  parts.push("family: '" + l.family + "'", 'difficulty: ' + D[l.difficulty]);
  return '  { ' + parts.join(', ') + ',\n    solution: [' + l.solution.map(pc).join(', ') + '] }';
});
console.log(`/* Perfect Fit — all ${LEVELS.length} levels stazzi ships (apps/casual/perfect-fit/src/levels/levels.ts, catalog 6, seed 6270), same order.
   Generated by tools/make-levels.mjs.
   map: board rows; '.' empty cell, ' ' not part of the board. Cell = [row, col] from the top-left.
   nums: piece sizes (2–7), sum = number of '.' cells.
   mask: shaped builder — the 4×4 builder rows, '.' = cell you may draw on (no mask = full 4×4).
   clues: [row, col, size] — a piece covering that cell must have exactly that many squares.
   pairs: [r1, c1, r2, c2] — two dots; one piece covers both or neither.
   seams: [r1, c1, r2, c2] — two neighbouring cells that must belong to different pieces.
   family: stazzi's rule family (plain, numbers, dots, seams, dots-seams, numbers-seams).
   difficulty: 1 easy · 2 medium · 3 hard — stazzi's own label (easy / medium / hard).
   solution: stazzi's verified solution, one piece per entry as flat row,col pairs, in placement order; test.js replays it. */
Postie.addLevels('perfect-fit', [
${rows.join(',\n')}
]);`);
