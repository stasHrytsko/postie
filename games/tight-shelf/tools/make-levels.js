/* Tight Shelf — builds levels.js from stazzi's 17 boards (apps/casual/tight-shelf/src/levels/levels.json, copied below).
   For each board: queue seed = stazzi's fixed seed where it has one (level 1: 26), otherwise the smallest seed >= 1 on which
   the preview bot (port of stazzi tools/bot.ts: sees the current piece + 2 next, likes lines and free room) reaches 5 lines.
   The bot's taps become `solution`. Difficulty = win rate of the "blind" bot (no preview: best spot for the current piece only,
   lines first, then free room — stazzi's `blind` bot from tools/tight-shelf-solver.mjs) over queue seeds 1..RUNS, no timer:
   >= 0.9 -> 1 easy, >= 0.6 -> 2 medium, else 3 hard. (The preview bot wins almost everything, so it can't rank boards.)
   Run: node games/tight-shelf/tools/make-levels.js > games/tight-shelf/levels.js */
global.Postie = require('../../../web/kit/kit.js');
require('../engine.js');
var E = Postie.engines['tight-shelf'];
var BOARDS = [
  ['....', 't...', '.ss.', '..Y.'], ['ot.Y', '...s', '....', 'C.B.'], ['.t.B', 'o.Ys', '.tC.', '...t'], ['.C.t', 'B.oB', 'st..', '.YYs'],
  ['.Bo.', 'soCs', 'tos.', '.Ys.'], ['.CBt', 'oYC.', '.oBs', 'sCo.'], ['sCBC', '.sso', 'Y.C.', 'YsYt'], ['Yss.', 'YBsB', 'Csoo', 'tY.B'],
  ['stso', 'BCoB', 'sst.', 'CttY'], ['CYBo', 'BtBY', 'toso', 'Bsso'], ['stsB', 'BoBt', 'tCCY', 'YCCt'], ['YsCs', 'tYto', 'tYsY', 'YsCB'],
  ['otYB', 'CsYt', 'tYBC', 'YYBY'], ['osss', 'ssoY', 'Bsss', 'ttCC'], ['BttY', 'tBso', 'CoBB', 'stBt'],
  ['oBoCo', 'ottYB', 'BoosB', 'YoYtY', 'YBYst'], ['oCoBYC', 'YCstBo', 'oBoCsY', 'oYCBoo', 'CsosYo', 'BCsooY']
];
var FIXED = { 1: 26 }, RUNS = +(process.env.RUNS || 400);

function evalBoard(rules, board) {
  var empty = 0, can = {};
  board.forEach(function (x, i) { if (x) return; empty++; E.TYPES.forEach(function (t) { if (E.fits(rules[i], t)) can[t] = 1; }); });
  return empty + 0.3 * Object.keys(can).length;
}
function best(s, board, t, depth) {
  if (depth === 0) return evalBoard(s.rules, board);
  var p = s.queue[t]; if (!p) return evalBoard(s.rules, board);
  var mv = E.legal(s.rules, board, p); if (!mv.length) return -1e4;
  var top = -Infinity;
  mv.forEach(function (c) { var b = board.slice(), r = E.put(b, c, p); top = Math.max(top, r.lines * 10 + best(s, b, t + 1, depth - 1)); });
  return top;
}
function botCell(s, depth) {
  var choice = -1, top = -Infinity, p = s.queue[0];
  E.legalNow(s).forEach(function (c) { var b = s.board.slice(), r = E.put(b, c, p), sc = r.lines * 10 + best(s, b, 1, depth - 1); if (sc > top) { top = sc; choice = c; } });
  return choice;
}
function play(L, seed, depth) {
  var s = E.fresh({ rules: L, target: 5, seed: seed }), cells = [];
  while (s.status === 'playing' && cells.length < 300) { var c = botCell(s, depth || 3); cells.push(c); E.move(s, c); }
  return { won: s.status === 'won', cells: cells };
}
var out = [];
BOARDS.forEach(function (L, k) {
  var id = k + 1, seed = FIXED[id], res;
  if (seed) res = play(L, seed); else for (seed = 1; !(res = play(L, seed)).won; seed++);
  var wins = 0; for (var i = 1; i <= RUNS; i++) if (play(L, i, 1).won) wins++;
  var rate = wins / RUNS, d = rate >= 0.9 ? 1 : rate >= 0.6 ? 2 : 3;
  if (!res.won) throw new Error('bot fails level ' + id);
  out.push('  { rules: ' + JSON.stringify(L).replace(/,/g, ', ') + ', seed: ' + seed + ', difficulty: ' + d + ', /* blind bot ' + Math.round(rate * 100) + '% */\n    solution: ' + JSON.stringify(res.cells) + ' }');
  console.error('level', id, 'seed', seed, 'blind bot win', rate.toFixed(2), 'moves', res.cells.length, 'difficulty', d);
});
console.log('/* Tight Shelf — all 17 levels from stazzi (apps/casual/tight-shelf/src/levels/levels.json), same order. Generated by tools/make-levels.js.\n' +
  '   rules: board rows top to bottom, one char per cell: \'.\' any piece, B blue / Y yellow / C coral = that colour, o circle / s square / t triangle = that shape.\n' +
  '   4×4, level 16 is 5×5, level 17 is 6×6. Goal everywhere: 5 lines (stazzi target).\n' +
  '   seed: the fixed queue seed (mulberry32 bag of 9 pieces, see engine.js) — the same queue on every attempt.\n' +
  '   difficulty: 1 easy · 2 medium · 3 hard, from the no-preview bot\'s win rate over ' + RUNS + ' queues (see tools/make-levels.js).\n' +
  '   solution: cells tapped in order (i = row * n + col), the bot\'s game on this seed; test.js replays it to 5 lines. */\n' +
  'Postie.addLevels(\'tight-shelf\', [\n' + out.join(',\n') + '\n]);');
